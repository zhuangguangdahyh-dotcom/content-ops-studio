function clone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

function setAtPath(value: unknown, pathParts: string[], replacement: unknown): void {
  let target = value as Record<string, unknown>;
  for (const part of pathParts.slice(0, -1)) target = target[part] as Record<string, unknown>;
  const key = pathParts.at(-1);
  if (key) target[key] = replacement;
}

async function writeJson(file: string, value: unknown): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

